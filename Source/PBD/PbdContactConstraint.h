#pragma once

#include <vector>
#include <DirectXMath.h>
#include "PbdCollision.h"

namespace PBD
{
	// ------------------------------------------------------------
	// contact_constraint
	//
	// Solverレベルで使用される、
	// 「めり込み禁止」を表す拘束（Constraint）。
	// これは衝突判定結果（body_contact）から生成され、
	// Solver が Projection（位置補正）を行うために必要な
	// 最小限の情報のみを保持する。
	// PBDでは、衝突を「拘束条件」として扱う。
	//
	// ------------------------------------------------------------
	//
	// 拘束式（Constraint formulation）:
	//
	//   phi(x) ≥ 0
	//
	// ここで:
	//
	//   phi(x)
	//      = 2つの物体間の符号付き距離
	//
	// Interpretation（意味）:
	//
	//   phi < 0
	//      → めり込んでいる（拘束違反）
	//
	//   phi = 0
	//      → 接触している
	//
	//   phi > 0
	//      → 離れている
	//
	// Solverは Projection 中に位置補正を行い、
	//
	//   phi ≥ 0
	//
	// を満たすように修正する。
	//
	// ------------------------------------------------------------
	// Notes:
	//
	// - これは Position Based Dynamics(PBD) の拘束
	// - Velocity（速度）は保持しない
	// - 反復型Gauss-Seidel Solver向け設計
	// - 将来的に XPBD の 入（ラグランジュ乗数）など
	//   Solver状態を追加可能
	// ------------------------------------------------------------
	struct ContactConstraint
	{
		// --------------------------------------------------------
		// a, b
		//
		// 衝突している2つのBodyを識別するハンドル。
		//
		// Solverはこれを使って、
		// ParticleやRigidBodyへアクセスする。
		//
		// Static Body（静的オブジェクト）は通常、
		// 無限質量を持ち、Projection時に動かない。
		// --------------------------------------------------------
		body_handle a;
		body_handle b;

		// --------------------------------------------------------
		// normal
		//
		// ワールド空間での接触法線ベクトル。
		//
		// Position Correction（位置補正）の方向を定義する。
		//
		// 必ず正規化（長さ1）されている必要がある。
		//
		// Convention（向きのルール）: Body B → Body A 方向を向く。
		//
		// つまり、「AをBから押し出す方向」。
		// --------------------------------------------------------
		DirectX::XMFLOAT3 normal;

		// --------------------------------------------------------
		// phi (constraint value)
		//
		// 2つのBody間の符号付き距離。
		//
		//   phi < 0
		//      → めり込み
		//
		//   phi = 0
		//      → 接触
		//
		//   phi > 0
		//      → 分離
		//
		// Solverは:
		//
		//   phi ≥ 0
		//
		// を満たすように補正を行う。
		//
		// 実際には、「どれだけ押し戻す必要があるか」を表す非常に重要な値。
		// --------------------------------------------------------

		float phi;

		// --------------------------------------------------------
		// stiffness
		// Constraint（拘束）の硬さ。
		// Range: [0, 1]
		//   1.0 → 完全に硬い拘束（強く押し戻す）
		//   <1  → 柔らかい拘束（安定するが少し沈み込む）
		// 小さくすると:
		// - プルプル感
		// - 柔らかさ
		// - 安定性向上
		// 
	    // XPBDでは通常、
		// stiffness の代わりに
		// compliance（柔らかさ）を使う。
		// --------------------------------------------------------
		float stiffness = 1.0f;
	};

	// ------------------------------------------------------------
	// to_contact_constraint
	//
	// Collision Detection（衝突検出）の結果
	// body_contact を、
	//
	// Solverが扱える contact_constraint に変換する関数。
	//
	// ------------------------------------------------------------
	// Input:
	//
	//   bc
	//      → 衝突判定結果
	//         （接触点・法線・phiなど）
	//
	//   stiffness
	//      → 拘束の硬さ（省略可能）
	//
	// ------------------------------------------------------------
	// Output:
	//
	//   Solverで使用される
	//   contact_constraint
	//
	// ------------------------------------------------------------
	// Responsibilities（役割）:
	//
	//   1. Body Handleをコピー
	//
	//   2. Contact Normalを転送
	//
	//   3. Signed Distance phi を転送
	//
	//   4. stiffness を設定
	//
	// ------------------------------------------------------------
	// この関数は:
	//
	//   Collision Detection
	//            ↓
	//   Constraint Solver
	//
	// を繋ぐ「橋渡し」の役割を持つ。
	//
	// Physics Engineでは非常に重要な層。
	// ------------------------------------------------------------
	ContactConstraint to_contact_constraint(
		const body_contact& bc,
		float stiffness = 1.0f);

}